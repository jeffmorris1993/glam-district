/* ── Top bar ──────────────────────────────────────────────────────── */

export function TopBar() {
  const phase = useStore((s) => s.phase);
  const focus = useStore((s) => s.focus);
  const setHovered = useStore((s) => s.setHovered);
  const focusBuilding = useStore((s) => s.focusBuilding);
  const openAgentPanel = useStore((s) => s.openAgentPanel);
  const status = useStatus();
  const visible = phase !== "arrival";

  return (
    <div
      className="pointer-events-none absolute inset-x-0 top-0 z-30 transition-all duration-700"
      style={{
        opacity: visible ? 1 : 0,
        transform: visible ? "none" : "translateY(-12px)",
        transitionTimingFunction: "var(--ease)",
      }}
    >
      <div className="flex items-start justify-between gap-4 px-5 py-4 sm:px-7 sm:py-5">
        <div className="pointer-events-auto flex items-center gap-4">
          <button
            type="button"
            onClick={() => focusBuilding(null)}
            className="text-left transition-opacity duration-300 hover:opacity-70"
            title="Return to the district"
          >
            <Wordmark small />
          </button>
        </div>

        {/* destination nav */}
        <div className="pointer-events-auto hidden items-center gap-1 rounded-full border border-[rgba(58,43,35,.1)] bg-[rgba(253,251,248,.72)] p-1 backdrop-blur-xl md:flex">
          {ORDER.map((id) => {
            const active = focus === id;
            const tone = TONE[status[id]];
            return (
              <button
                key={id}
                type="button"
                onMouseEnter={() => phase === "district" && setHovered(id)}
                onMouseLeave={() => setHovered(null)}
                onClick={() => {
                  openAgentPanel(null);
                  focusBuilding(id);
                }}
                className="group relative flex items-center gap-2 rounded-full px-3.5 py-[7px] transition-colors duration-300"
                style={{ background: active ? "var(--espresso)" : "transparent" }}
              >
                <span className="h-[5px] w-[5px] shrink-0 rounded-full" style={{ background: tone.dot }} />
                <span
                  className="label text-[9.5px] transition-colors"
                  style={{ color: active ? "#FBF7F2" : "#6E5C4D" }}
                >
                  {SITES[id].name.replace("The ", "")}
                </span>
              </button>
            );
          })}
        </div>

        <div
          className="pointer-events-auto flex items-center gap-2.5 transition-opacity duration-500"
          style={{ opacity: phase === "building" ? 0 : 1 }}
        >
          <DemoBadge compact />
        </div>
      </div>

      {/* compact destination switcher for narrow screens */}
      <div className="pointer-events-auto mx-5 -mt-1 flex items-center gap-1 rounded-full border border-[rgba(58,43,35,.1)] bg-[rgba(253,251,248,.78)] p-1 backdrop-blur-xl md:hidden">
        {ORDER.map((id) => {
          const active = focus === id;
          const tone = TONE[status[id]];
          return (
            <button
              key={id}
              type="button"
              onClick={() => {
                openAgentPanel(null);
                focusBuilding(id);
              }}
              className="flex flex-1 items-center justify-center gap-1.5 rounded-full px-2 py-[7px] transition-colors duration-300"
              style={{ background: active ? "var(--espresso)" : "transparent" }}
            >
              <span className="h-[5px] w-[5px] shrink-0 rounded-full" style={{ background: tone.dot }} />
              <span
                className="label text-[8.5px]"
                style={{ color: active ? "#FBF7F2" : "#6E5C4D" }}
              >
                {SITES[id].name.replace("The ", "").split(" ")[0]}
              </span>
            </button>
          );
        })}
      </div>
    </div>
  );
}

/* ── The hero control ─────────────────────────────────────────────── */

export function ScenarioBar() {
  const phase = useStore((s) => s.phase);
  const scenario = useStore((s) => s.scenario);
  const running = useStore((s) => s.running);
  const stage = useStore((s) => s.viralStage);
  const run = useStore((s) => s.runViralDrop);
  const reset = useStore((s) => s.resetSimulation);
  const visible = phase !== "arrival";

  const stages = ["Boutique", "Fulfillment", "Atelier", "Concierge"];

  return (
    <div
      className="pointer-events-none absolute inset-x-0 bottom-0 z-30 flex justify-center px-5 pb-5 transition-all duration-700 sm:pb-7"
      style={{
        opacity: visible ? 1 : 0,
        transform: visible ? "none" : "translateY(16px)",
        transitionTimingFunction: "var(--ease)",
      }}
    >
      <div className="panel grain pointer-events-auto relative overflow-hidden rounded-full">
        <div className="goldline absolute inset-x-0 top-0 h-px" />
        <div className="flex items-center gap-1 p-1.5">
          {scenario === "baseline" ? (
            <button
              type="button"
              onClick={run}
              className="group relative overflow-hidden rounded-full bg-[var(--espresso)] px-5 py-[10px] text-[#FBF7F2] transition-all duration-500 hover:bg-[var(--ink)]"
            >
              <span className="label relative z-10 flex items-center gap-2.5 text-[10px]">
                <SparkIcon />
                Simulate a Viral Drop
              </span>
              <span
                className="absolute inset-y-0 -left-1/2 w-1/2 opacity-0 group-hover:opacity-100"
                style={{
                  background: "linear-gradient(90deg, transparent, rgba(232,209,164,.4), transparent)",
                  animation: "sweep 1.5s var(--ease) infinite",
                }}
              />
            </button>
          ) : (
            <>
              <div className="flex items-center gap-3.5 rounded-full bg-[rgba(58,43,35,.05)] px-4 py-[9px]">
                <span className="eyebrow hidden text-[8.5px] text-[#8C7B66] sm:inline">Viral Drop</span>
                <div className="flex items-center gap-1.5">
                  {stages.map((s, i) => {
                    const done = stage >= i + 1;
                    const current = stage === i + 1 && running;
                    return (
                      <span key={s} className="flex items-center gap-1.5" title={s}>
                        <span
                          className={`h-[6px] w-[6px] rounded-full transition-all duration-500 ${current ? "a-breathe" : ""}`}
                          style={{
                            background: done ? "var(--gold)" : "rgba(58,43,35,.16)",
                            transform: done ? "scale(1)" : "scale(.8)",
                          }}
                        />
                        {i < stages.length - 1 && (
                          <span
                            className="h-px w-3 transition-colors duration-500"
                            style={{ background: stage >= i + 2 ? "var(--champagne)" : "rgba(58,43,35,.12)" }}
                          />
                        )}
                      </span>
                    );
                  })}
                </div>
                <span className="num whitespace-nowrap pl-1 text-[10.5px] text-[var(--espresso)]">
                  {stage >= 4 ? "Complete" : `Stage ${Math.max(1, stage)} of 4`}
                </span>
              </div>
              <span className="mx-1 h-5 w-px bg-[rgba(58,43,35,.12)]" />
              <Btn variant="quiet" onClick={reset} size="sm" className="mr-1">
                Reset Simulation
              </Btn>
            </>
          )}
        </div>
      </div>
    </div>
  );
}

