const ORDER: BuildingId[] = ["fulfillment", "atelier", "boutique"];

function useStatus(): Record<BuildingId, WorldStatus> {
  const m = useStore((s) => s.metrics);
  return {
    fulfillment: m.fulfillment.status,
    atelier: m.inventory.status,
    boutique: m.boutique.status,
  };
}

